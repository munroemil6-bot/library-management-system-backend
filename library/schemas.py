from marshmallow import fields, validate
from marshmallow_sqlalchemy import SQLAlchemyAutoSchema, auto_field
from models import Author, Category, Book  # Import your SQLAlchemy models


class AuthorSchema(SQLAlchemyAutoSchema):
    class Meta:
        model = Author
        load_instance = True  # Automatically deserializes JSON straight into Author model instances
        include_fk = True

    # Custom field validations
    id = auto_field(dump_only=True)  # Auto-generated by DB, so read-only
    name = auto_field(required=True, validate=validate.Length(min=1, max=100))
    bio = auto_field()


class CategorySchema(SQLAlchemyAutoSchema):
    class Meta:
        model = Category
        load_instance = True
        include_fk = True

    id = auto_field(dump_only=True)
    name = auto_field(required=True, validate=validate.Length(min=1, max=50))
    description = auto_field()


class BookSchema(SQLAlchemyAutoSchema):
    class Meta:
        model = Book
        load_instance = True
        include_fk = True  # Ensures author_id and category_id are accepted/outputted

    id = auto_field(dump_only=True)
    title = auto_field(required=True, validate=validate.Length(min=1, max=200))
    isbn = auto_field(validate=validate.Length(equal=13))
    publication_year = auto_field()

    # Optional: Nested display for GET responses (shows names instead of just IDs)
    author = fields.Nested(AuthorSchema, only=("id", "name"), dump_only=True)
    category = fields.Nested(CategorySchema, only=("id", "name"), dump_only=True)

