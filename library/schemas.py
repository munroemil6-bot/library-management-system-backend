from .extensions import ma
from .models import User, BorrowRecord
from marshmallow import fields, validate, validates, ValidationError, validates_schema
from marshmallow_sqlalchemy import SQLAlchemyAutoSchema, auto_field
from .models import Author, Category, Book # Import your SQLAlchemy models

# MASON — Authentication & Users
class UserSchema(ma.SQLAlchemyAutoSchema):
    class Meta:
        model = User
        dump_only = ("id", "username", "email", "role", "created_at")

    password = fields.String(load_only=True)


class RegisterSchema(ma.Schema):
    username = fields.String(required=True, validate=validate.Length(min=1))
    email = fields.Email(required=True)
    password = fields.String(required=True, validate=validate.Length(min=8), load_only=True)
    password_confirmation = fields.String(required=True, load_only=True)

    @validates("username")
    def validate_username_unique(self, value):
        if User.query.filter_by(username=value).first():
            raise ValidationError("Username already taken.")

    @validates("email")
    def validate_email_unique(self, value):
        if User.query.filter_by(email=value).first():
            raise ValidationError("Email already registered.")

    @validates_schema
    def validate_passwords(self, data, **kwargs):
        if data["password"] != data["password_confirmation"]:
            raise ValidationError(
                {"password_confirmation": ["Passwords do not match."]}
            )


class LoginSchema(ma.Schema):
    email = fields.Email(required=True)
    password = fields.String(required=True, load_only=True)


# NAOMI — Library Management
class AuthorSchema(SQLAlchemyAutoSchema):
    class Meta:
        model = Author
        load_instance = True  # Automatically deserializes JSON straight into Author model instances
        include_fk = True

    # Custom field validations
    id = auto_field(dump_only=True)  # Auto-generated by DB, so read-only
    name = auto_field(required=True, validate=validate.Length(min=1, max=100))
    biography = auto_field()


class CategorySchema(SQLAlchemyAutoSchema):
    class Meta:
        model = Category
        load_instance = True
        include_fk = True

    id = auto_field(dump_only=True)
    name = auto_field(required=True, validate=validate.Length(min=1, max=50))
    description = auto_field()


class BookSchema(SQLAlchemyAutoSchema):
    class Meta:
        model = Book
        load_instance = True
        include_fk = True  # Ensures author_id and category_id are accepted/outputted

    id = auto_field(dump_only=True)
    title = auto_field(required=True, validate=validate.Length(min=1, max=200))
    isbn = auto_field(validate=validate.Length(equal=13))
    published_year = auto_field()

    # Optional: Nested display for GET responses (shows names instead of just IDs)
    author = fields.Nested(AuthorSchema, only=("id", "name"), dump_only=True)
    category = fields.Nested(CategorySchema, only=("id", "name"), dump_only=True)

# NASRA — Borrowing System
class BorrowSchema(ma.SQLAlchemyAutoSchema):
    class Meta:
        model = BorrowRecord
        dump_only = ("id", "borrow_date", "status")

    user = fields.Nested(UserSchema, dump_only=True)
    book = fields.Nested("BookSchema", dump_only=True)
